#Enunciado
#Peça três notas ao usuário.
#Calcule a média aritmética: some as notas e divida por 3.
#Mostre o resultado com duas casas decimais.

av1 = float(input("Escreva a nota 1: "))
av2 = float(input("Escreva a nota 2: "))
av3 = float(input("Escreva a nota 3: "))

media = (av1 + av2 + av3) / 3

print(f"Sua média é: {media}")