#Criando variaveis com diferentes tipos de dados

idade = 20
altura = 1.89
nome = "Alan"
estudando = True

#Mostrando os tipos de dados de cada variavel
print(f"O tipo da variavel idade é {type(idade)}")
print(f"O tipo da variavel altura é {type(altura)}")
print(f"O tipo da variavel nome é {type(nome)}")
print(f"O tipo da variavel estudando é {type(estudando)}")

#A função type(), informa o tipo de dado que a variavel guarda (inteiro,float(ou real),booleano e string)
